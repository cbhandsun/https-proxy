  "        foreach ($pair in @(@($node,$staging.nodeSha256),@($manifest,$staging.manifestSha256),@((Join-Path $OwnedRoot 'clients/codex.exe'),$staging.codexSha256),@((Join-Path $OwnedRoot 'clients/claude.exe'),$staging.claudeSha256))) {",
